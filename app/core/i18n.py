def resolve_lang(request) -> str:
    """Мова з cookie, інакше з Accept-Language, інакше DEFAULT_LANG."""
    cookie = request.cookies.get("lang")
    if cookie in TRANSLATIONS:
        return cookie

    header = request.headers.get("accept-language", "")
    for chunk in header.split(","):
        code = chunk.split(";")[0].strip().lower()[:2]
        if code in TRANSLATIONS:
            return code
    return DEFAULT_LANG


def translate(lang: str, key: str) -> str:
    """Переклад з відкатом на українську, потім на сам ключ."""
    table = TRANSLATIONS.get(lang) or TRANSLATIONS[DEFAULT_LANG]
    if key in table:
        return table[key]
    return TRANSLATIONS[DEFAULT_LANG].get(key, key)


def make_translator(lang: str):
    """Готова функція t() для передачі в шаблон."""
    return lambda key: translate(lang, key)
